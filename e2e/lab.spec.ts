test('拖入仪器、移动仪器、键盘移动与选择', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: '实验仪器', exact: true }).click()
  const source = page.locator('.library-item').filter({ hasText: '烧杯' })
  await source.dragTo(page.getByTestId('bench'), { targetPosition: { x: 360, y: 240 } })
  const object = page.locator('.bench-object.object-beaker')
  await expect(object).toHaveCount(1)
  const before = (await object.boundingBox())!
  await page.mouse.move(before.x + before.width / 2, before.y + before.height / 2)
  await page.mouse.down()
  await page.mouse.move(before.x + before.width / 2 + 60, before.y + before.height / 2 + 25, {
    steps: 6,
  })
  await page.mouse.up()
  const after = (await object.boundingBox())!
  expect(after.x).toBeGreaterThan(before.x + 45)
  await object.focus()
  await page.keyboard.press('ArrowLeft')
  expect((await object.boundingBox())!.x).toBeLessThan(after.x)
})
test('过氧化氢：连接、催化、暂停、回放与微观视图', async ({ page }) => {
  await page.clock.install()
  await page.goto('/')
  await page.locator('.guide-action').click()
  await expect(page.locator('.connection-layer path')).toHaveCount(3)
  await page.locator('.guide-action').click()
  await page.clock.runFor(2000)
  await page.locator('.guide-action').click()
  await page.clock.runFor(5000)
  await expect(page.locator('.analysis')).toContainText('MnO₂')
  await expect(page.locator('.product-amount').last()).not.toHaveText('0.00')
  await page.getByRole('button', { name: '暂停反应', exact: true }).click()
  const time = await page.locator('.playback-time').innerText()
  const image = await page
    .locator('.reaction-canvas')
    .first()
    .evaluate((c: HTMLCanvasElement) => c.toDataURL())
  await page.clock.runFor(1000)
  expect(await page.locator('.playback-time').innerText()).toBe(time)
  expect(
    await page
      .locator('.reaction-canvas')
      .first()
      .evaluate((c: HTMLCanvasElement) => c.toDataURL()),
  ).toBe(image)
  await page.getByRole('button', { name: '返回反应前', exact: true }).click()
  await expect(page.locator('.playback-time')).toContainText('00:00')
  await page.getByRole('button', { name: '微观模式', exact: true }).click()
  await expect(page.locator('.micro-view canvas')).toBeVisible()
  await expect(page.locator('.micro-view')).toContainText('H₂O₂')
})
